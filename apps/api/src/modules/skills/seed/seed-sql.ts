import { join } from 'node:path';
import { normalizeSkillKey } from '@am/contracts';
import { API_ROOT, type SeedSkill } from './global-skills.js';

/** Where the generated migration lives. */
export const SEED_MIGRATION_PATH = join(API_ROOT, 'drizzle/0003_skills_seed.sql');

const literal = (text: string) => `'${text.replaceAll("'", "''")}'`;

const BREAKPOINT = '--> statement-breakpoint';

/**
 * The SQL of the seed migration, from the reviewed list: the keys come from `normalizeSkillKey`, so
 * the database and the API agree on them. `ON CONFLICT DO NOTHING` makes a second run harmless.
 * The file is generated and never edited by hand (`pnpm --filter @am/api seed:generate`).
 */
export function buildSeedSql(skills: SeedSkill[]): string {
  const skillRows = skills.map(
    (skill) => `  (${literal(skill.name)}, ${literal(normalizeSkillKey(skill.name))}, ${literal(skill.category)})`,
  );
  const aliasRows = skills.flatMap((skill) =>
    skill.aliases.map(
      (alias) => `    (${literal(normalizeSkillKey(skill.name))}, ${literal(alias)}, ${literal(normalizeSkillKey(alias))})`,
    ),
  );

  return [
    '-- Generated by `pnpm --filter @am/api seed:generate` from src/modules/skills/seed/global-skills.json.',
    '-- Do not edit by hand: change the JSON and generate again.',
    'INSERT INTO "skills"."skills" ("name", "normalized_key", "category") VALUES',
    `${skillRows.join(',\n')}`,
    'ON CONFLICT DO NOTHING;',
    BREAKPOINT,
    'INSERT INTO "skills"."skill_aliases" ("skill_id", "alias", "normalized_alias")',
    'SELECT s."id", v."alias", v."normalized_alias"',
    'FROM (VALUES',
    `${aliasRows.join(',\n')}`,
    ') AS v("skill_key", "alias", "normalized_alias")',
    'JOIN "skills"."skills" s ON s."normalized_key" = v."skill_key" AND s."owner_user_id" IS NULL',
    'ON CONFLICT DO NOTHING;',
    '',
  ].join('\n');
}
