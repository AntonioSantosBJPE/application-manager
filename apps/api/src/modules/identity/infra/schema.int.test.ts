import { join } from 'node:path';
import pg from 'pg';
import { afterAll, beforeAll, describe, expect, inject, it } from 'vitest';
import { runMigrations } from '../../../infra/database/migrations.js';

const migrationsFolder = join(import.meta.dirname, '../../../../drizzle');

/** A database of its own, migrated once, so the assertion is about what the migrations create. */
async function createMigratedDatabase(): Promise<string> {
  const url = new URL(inject('databaseUrl'));
  const name = `identity_schema_${process.pid}_${Math.random().toString(36).slice(2, 10)}`;
  const admin = new pg.Client({ connectionString: url.href });
  await admin.connect();
  await admin.query(`create database ${name}`);
  await admin.end();
  url.pathname = `/${name}`;
  const href = url.href;
  await runMigrations({ databaseUrl: href, migrationsFolder });
  return href;
}

async function query<T extends pg.QueryResultRow>(databaseUrl: string, text: string, values?: unknown[]): Promise<T[]> {
  const client = new pg.Client({ connectionString: databaseUrl });
  await client.connect();
  try {
    return (await client.query<T>(text, values)).rows;
  } finally {
    await client.end();
  }
}

describe('identity schema', () => {
  let databaseUrl: string;

  beforeAll(async () => {
    databaseUrl = await createMigratedDatabase();
  }, 60_000);

  afterAll(async () => {
    const url = new URL(databaseUrl);
    const name = url.pathname.slice(1);
    url.pathname = '/postgres';
    const admin = new pg.Client({ connectionString: url.href });
    await admin.connect();
    await admin.query(`drop database if exists ${name} with (force)`);
    await admin.end();
  });

  it('has four tables uuidv7 keys and no foreign key to another schema', async () => {
    const tables = await query<{ table_name: string }>(
      databaseUrl,
      "select table_name from information_schema.tables where table_schema = 'identity' order by table_name",
    );
    expect(tables.map((t) => t.table_name)).toEqual(['invitations', 'login_attempts', 'sessions', 'users']);

    // Every key is generated by uuidv7() in Postgres, not by the application.
    const keyDefaults = await query<{ table_name: string; column_default: string }>(
      databaseUrl,
      `select table_name, column_default
         from information_schema.columns
        where table_schema = 'identity' and column_name = 'id'
        order by table_name`,
    );
    expect(keyDefaults.map((c) => [c.table_name, c.column_default])).toEqual([
      ['invitations', 'uuidv7()'],
      ['login_attempts', 'uuidv7()'],
      ['sessions', 'uuidv7()'],
      ['users', 'uuidv7()'],
    ]);

    // No foreign key leaves the schema: the module can be extracted without a rewrite.
    const outside = await query<{ constraint_name: string; target_schema: string }>(
      databaseUrl,
      `select c.conname as constraint_name, target_ns.nspname as target_schema
         from pg_constraint c
         join pg_class source_table on source_table.oid = c.conrelid
         join pg_namespace source_ns on source_ns.oid = source_table.relnamespace
         join pg_class target_table on target_table.oid = c.confrelid
         join pg_namespace target_ns on target_ns.oid = target_table.relnamespace
        where c.contype = 'f' and source_ns.nspname = 'identity' and target_ns.nspname <> 'identity'`,
    );
    expect(outside).toEqual([]);

    // Control: the scan sees the foreign keys that do exist, both staying inside the schema.
    const inside = await query<{ constraint_name: string }>(
      databaseUrl,
      `select c.conname as constraint_name
         from pg_constraint c
         join pg_class source_table on source_table.oid = c.conrelid
         join pg_namespace source_ns on source_ns.oid = source_table.relnamespace
        where c.contype = 'f' and source_ns.nspname = 'identity'
        order by c.conname`,
    );
    expect(inside.map((c) => c.constraint_name)).toEqual([
      'invitations_invited_by_users_id_fk',
      'sessions_user_id_users_id_fk',
    ]);
  });

  it('keeps one pending invitation per email', async () => {
    const [admin] = await query<{ id: string }>(
      databaseUrl,
      "insert into identity.users (email, name, password_hash, role) values ($1, $2, $3, 'admin') returning id",
      ['admin@example.com', 'Admin', 'x'],
    );
    const insert = (email: string) =>
      query(
        databaseUrl,
        `insert into identity.invitations (email, token_hash, invited_by, expires_at)
         values ($1, $2, $3, now() + interval '7 days')`,
        [email, `hash-${email}-${Math.random()}`, admin!.id],
      );

    await insert('novo@example.com');
    await expect(insert('novo@example.com')).rejects.toThrow(/invitations_pending_email_unique/);

    // The partial index only guards pending ones: a revoked row frees the email.
    await query(databaseUrl, "update identity.invitations set revoked_at = now() where email = 'novo@example.com'");
    await expect(insert('novo@example.com')).resolves.toBeDefined();
  });

  it('drops the sessions of a deleted user', async () => {
    const [user] = await query<{ id: string }>(
      databaseUrl,
      "insert into identity.users (email, name, password_hash, role) values ($1, $2, $3, 'member') returning id",
      ['cascade@example.com', 'Cascade', 'x'],
    );
    await query(
      databaseUrl,
      "insert into identity.sessions (user_id, token_hash, expires_at) values ($1, $2, now() + interval '30 days')",
      [user!.id, `session-${user!.id}`],
    );

    await query(databaseUrl, 'delete from identity.users where id = $1', [user!.id]);

    expect(await query(databaseUrl, 'select id from identity.sessions where user_id = $1', [user!.id])).toEqual([]);
  });
});
